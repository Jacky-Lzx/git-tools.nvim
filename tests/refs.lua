local root = vim.env.GIT_TOOLS_ROOT or vim.fn.getcwd()
vim.opt.rtp:prepend(root)
local test = dofile(root .. "/tests/helpers.lua")
local git, branches, stash = require("git_tools.git"), require("git_tools.branches"), require("git_tools.stash")
local f = test.fixture()
f:write("file", { "base" })
f:git("add", ".")
f:git("commit", "-qm", "initial")
local task = git.task()
local repo = test.await(function(cb)
  git.discover(task, { cwd = f.root }, cb)
end)
local function list()
  return test.await(function(cb)
    branches.query(task, repo, { all = true }, cb)
  end)
end
local function find(name)
  for _, item in ipairs(list()) do
    if item.name == name then
      return item
    end
  end
  error("Missing branch " .. name)
end
assert(find("main").current)
test.await(function(cb)
  branches.create(repo, "feature/test", {}, cb)
end)
test.await(function(cb)
  branches.switch(find("feature/test"), {}, cb)
end)
assert(f:git("branch", "--show-current") == "feature/test\n")
vim.cmd.edit(f.root .. "/file")
vim.api.nvim_buf_set_lines(0, 0, -1, false, { "unsaved" })
local err = test.result(function(cb)
  branches.switch(find("main"), {}, cb)
end)
assert(err and err:find("Unsaved buffer", 1, true))
vim.cmd.bwipeout({ bang = true })
test.await(function(cb)
  branches.switch(find("main"), {}, cb)
end)
test.await(function(cb)
  branches.delete(find("feature/test"), {
    confirm = function()
      return true
    end,
  }, cb)
end)
assert(#list() == 1)
test.await(function(cb)
  branches.create(repo, "unmerged", {}, cb)
end)
test.await(function(cb)
  branches.switch(find("unmerged"), {}, cb)
end)
f:write("file", { "branch commit" })
f:git("add", ".")
f:git("commit", "-qm", "unmerged")
test.await(function(cb)
  branches.switch(find("main"), {}, cb)
end)
err = test.result(function(cb)
  branches.delete(find("unmerged"), {
    confirm = function()
      return true
    end,
  }, cb)
end)
assert(err and find("unmerged"), "Unmerged deletion must never be forced")
f:git("update-ref", "refs/remotes/origin/remote-topic", "HEAD")
f:git("remote", "add", "origin", f.root)
f:git("config", "remote.origin.fetch", "+refs/heads/*:refs/remotes/origin/*")
test.await(function(cb)
  branches.switch(find("origin/remote-topic"), {}, cb)
end)
assert(f:git("branch", "--show-current") == "remote-topic\n")
test.await(function(cb)
  branches.switch(find("main"), {}, cb)
end)
local tree = f.root .. "-worktree"
f:git("worktree", "add", "-qb", "in-worktree", tree)
err = test.result(function(cb)
  branches.delete(find("in-worktree"), {
    confirm = function()
      return true
    end,
  }, cb)
end)
assert(err and err:find("worktree", 1, true))
f:git("worktree", "remove", tree)
f:write("file", { "stashed" })
f:git("stash", "push", "-qm", "first")
local stashes = test.await(function(cb)
  stash.query(task, repo, cb)
end)
assert(#stashes == 1)
local patch = test.await(function(cb)
  stash.patch(task, stashes[1], cb)
end)
assert(table.concat(patch, "\n"):find("+stashed", 1, true))
-- Moving stash positions must not change the selected immutable object.
f:write("file", { "newer" })
f:git("stash", "push", "-qm", "second")
test.await(function(cb)
  stash.apply(stashes[1], {}, cb)
end)
assert(vim.fn.readfile(f.root .. "/file")[1] == "stashed" and #test.await(function(cb)
  stash.query(task, repo, cb)
end) == 2)
f:git("reset", "--hard", "HEAD")
f:write("file", { "conflicting local" })
f:git("add", ".")
f:git("commit", "-qm", "conflict")
err = test.result(function(cb)
  stash.apply(stashes[1], {}, cb)
end)
assert(err and f:git("ls-files", "-u") ~= "", "Conflicted apply must keep its result and report failure")
assert(#test.await(function(cb)
  stash.query(task, repo, cb)
end) == 2, "Apply must retain stash even on conflict")
f:git("reset", "--hard", "HEAD")
f:git("stash", "clear")
err = test.result(function(cb)
  stash.apply(stashes[1], {}, cb)
end)
assert(err and err:find("Stash list changed", 1, true))
f:cleanup()
print(
  "git refs: branch create/switch/delete, remote tracking, unsaved/worktree guards, stash preview/apply and immutable selection passed"
)
vim.cmd("qa!")
