vim.opt.rtp:prepend(vim.fn.getcwd())
local plugin = require("git_tools")
local commands, handlers = vim.api.nvim_get_commands({}), vim.api.nvim_get_autocmds({})
local cold = plugin.get_state()
assert(cold.initialized == false and cold.compare == nil and cold.signs == nil)
assert(not package.loaded["git_tools.buffer"] and not package.loaded["git_tools.view"])
assert(vim.deep_equal(commands, vim.api.nvim_get_commands({})))
assert(vim.deep_equal(handlers, vim.api.nvim_get_autocmds({})))
plugin.setup({ buffer = false })
local state = plugin.get_state()
assert(state.initialized and state.compare == false)
state.signs = true
assert(plugin.get_state().signs == false)
plugin.dispose()
assert(not plugin.get_state().initialized and plugin.get_state().signs == false)
print("Git public state: cold reads, resource isolation and snapshot ownership passed")
