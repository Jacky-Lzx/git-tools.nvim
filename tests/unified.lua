vim.opt.rtp:prepend(vim.env.GIT_TOOLS_ROOT or vim.fn.getcwd())
local diff = require("git_tools").diff
local buffers = vim.api.nvim_list_bufs()
local before, after = { "local value = 1", "return value" }, { "local value = 2", "return value" }
local copy = vim.deepcopy(before)
local patch = diff.unified(before, after, { old_path = "src/中文.lua", new_path = "src/中文.lua" })
assert(patch[1] == "--- src/中文.lua" and patch[2] == "+++ src/中文.lua")
local body = table.concat(patch, "\n")
assert(body:find("-local value = 1", 1, true) and body:find("+local value = 2", 1, true))
assert(vim.deep_equal(before, copy) and #diff.unified(before, before) == 0)
local insert = table.concat(diff.unified({}, { "😀hello" }), "\n")
assert(insert:find("@@ -0,0 +1 @@", 1, true) and insert:find("+😀hello", 1, true))
local delete = table.concat(diff.unified({ "gone" }, {}), "\n")
assert(delete:find("@@ -1 +0,0 @@", 1, true) and delete:find("-gone", 1, true))
assert(#diff.unified("hello", "hello\n") > 0, "string inputs retain final-newline differences")
assert(#diff.unified("", "") == 0 and #diff.unified({}, {}) == 0)
assert(not pcall(diff.unified, { "a\nb" }, {}))
assert(not pcall(diff.unified, { 1 }, {}))
assert(not pcall(diff.unified, {}, {}, { context = -1 }))
local zero = table.concat(diff.unified({ "a", "b", "c" }, { "a", "B", "c" }, { context = 0 }), "\n")
assert(not zero:find("\n a", 1, true) and not zero:find("\n c", 1, true))
assert(vim.deep_equal(buffers, vim.api.nvim_list_bufs()), "diff generation creates no source or scratch buffers")
assert(not package.loaded.selection_tools and not package.loaded["snacks"], "core has no picker dependency")
local provider = require("git_tools.integrations.selection").diff()
assert(type(provider) == "function" and not package.loaded.selection_tools)
assert(not provider({ item = "not a patch" }))
print("git-tools unified: Unicode, insert/delete, exact newlines, context, isolation and optional adapter passed")
vim.cmd("qa!")
